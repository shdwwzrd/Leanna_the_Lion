#define SCREEN_WIDTH  96
#define SCREEN_HEIGHT 64
#define BUFFER_SIZE   (SCREEN_WIDTH * SCREEN_HEIGHT)
#define COLOR8(r,g,b) ((b>>5)<<5|(g>>5)<<2|(r>>6))

#define SPRITE 0
#define SPRITE_WITH_MASK 1




unsigned char screen_buffer[BUFFER_SIZE];


//collision strcuts
struct Rect
{
  int16_t x;      
  int16_t y;      
  uint8_t width;  
  uint8_t height; 
};

struct Point
{
  int16_t x; 
  int16_t y; 
};


//Frame Rate handler
//uint8_t eachFrameMillis = 1000/60;
static const unsigned long eachFrameMillis = 1000000/60;
unsigned long lastFrameStart;
unsigned long nextFrameStart = 0;
uint16_t frameCount = -1;
unsigned long interval_time;
    
bool everyXFrames(uint8_t frames)
{
  return frameCount % frames == 0;
}

bool nextFrame()
{
  unsigned long now = micros();
  interval_time = now - lastFrameStart;
  if(interval_time < eachFrameMillis) return false;    
  
  lastFrameStart = now;
  frameCount++;
  
  return true;
}






//collision detection

bool collide(Point point, Rect rect)
{
  return ((point.x >= rect.x) && (point.x < rect.x + rect.width) &&
      (point.y >= rect.y) && (point.y < rect.y + rect.height));
}

bool collide(Rect rect1, Rect rect2)
{
  return !(rect2.x                >= rect1.x + rect1.width  ||
           rect2.x + rect2.width  <= rect1.x                ||
           rect2.y                >= rect1.y + rect1.height ||
           rect2.y + rect2.height <= rect1.y);
}

bool collide(Point first_point, Point second_point, Rect rect) {
  if (
    (first_point.x <= rect.x && second_point.x <= rect.x) ||
    (first_point.y <= rect.y && second_point.y <= rect.y) ||
    (first_point.x >= rect.x + rect.width && second_point.x >= rect.x + rect.width) ||
    (first_point.y >= rect.y + rect.height && second_point.y >= rect.y + rect.height)
  ) {
    return false;
  }

  float m = (second_point.y - first_point.y) / (second_point.x - first_point.x);

  float y = m * (rect.x - first_point.x) + first_point.y;
  if (y > rect.y && y < rect.y + rect.height) return true;

  y = m * (rect.x + rect.width - first_point.x) + first_point.y;
  if (y > rect.y && y < rect.y + rect.height) return true;

  float x = (rect.y - first_point.y) / m + first_point.x;
  if (x > rect.x && x < rect.x + rect.width) return true;

  x = (rect.y + rect.height - first_point.y) / m + first_point.x;
  if (x > rect.x && x < rect.x + rect.width) return true;

  return false;
}




//draw routines
void swap(int16_t& a, int16_t& b)
{
  int16_t temp = a;
  a = b;
  b = temp;
}

void drawLine(int16_t x0, int16_t y0, int16_t x1, int16_t y1, uint8_t color)
{
  // bresenham's algorithm - thx wikpedia
  bool steep = abs(y1 - y0) > abs(x1 - x0);
  if (steep) {
    swap(x0, y0);
    swap(x1, y1);
  }

  if (x0 > x1) {
    swap(x0, x1);
    swap(y0, y1);
  }

  int16_t dx, dy;
  dx = x1 - x0;
  dy = abs(y1 - y0);

  int16_t err = dx / 2;
  int8_t ystep;

  if (y0 < y1)
  {
    ystep = 1;
  }
  else
  {
    ystep = -1;
  }

  for (; x0 <= x1; x0++)
  {
    if (steep)
    {
      if(x0>=0 && x0<SCREEN_WIDTH && y0>=0 && y0<SCREEN_HEIGHT){
        screen_buffer[SCREEN_WIDTH * x0 + y0] = color;
      }
    }
    else
    {
      if(x0>=0 && x0<SCREEN_WIDTH && y0>=0 && y0<SCREEN_HEIGHT){
        screen_buffer[SCREEN_WIDTH * y0 + x0] = color;
      }
    }

    err -= dy;
    if (err < 0)
    {
      y0 += ystep;
      err += dx;
    }
  }
}

void drawHLine(int16_t x, int16_t y, int16_t w, uint8_t color)
{
  int end = x+w;
  for(int a = max(0,x); a < min(end,SCREEN_WIDTH); a++){
    screen_buffer[SCREEN_WIDTH * y + a] = color;
  }  
}

void drawVLine(int16_t x, int16_t y, int16_t h, uint8_t color)
{
  int end = y+h;
  for(int a = max(0,y); a < min(end,SCREEN_HEIGHT); a++){
    screen_buffer[SCREEN_WIDTH * a + x] = color;
  }  
}

void DrawSprite(int x, int y, const unsigned char* bitmap, int frame, int draw_mode)
{
  unsigned int palette_offset=3;//location of the color palette
  
  uint8_t scan_x;
  uint8_t scan_y;
  uint8_t image_width = pgm_read_byte(&bitmap[0]);//get image width  
  uint8_t image_height = pgm_read_byte(&bitmap[1]);//get image height  
  uint8_t palette_size = pgm_read_byte(&bitmap[2]);//get color palette size
  
  uint8_t ppb = 8;//2 colors
  uint8_t bpp = 1;
  uint8_t factor = 0b1;
  if(palette_size==256){//256 colors
    ppb = 1;
    bpp = 8;
    factor = 0b11111111;
  }else if(palette_size==16){//16 colors
    ppb = 2;
    bpp = 4;
    factor = 0b1111;
  }else if(palette_size==4){//4 colors
    ppb = 4;
    bpp = 2;
    factor = 0b11;
  }
  
  uint16_t bytes_per_frame = ((image_width * image_height) / ppb)+( image_height % 8 == 0 ? 0 : 1);
  uint16_t bytes_per_mask = ((image_width * image_height) / 8)+( image_height % 8 == 0 ? 0 : 1);
  int source_address = palette_size + palette_offset + frame * bytes_per_frame;
  if(draw_mode == SPRITE_WITH_MASK){
    source_address = palette_size + palette_offset + frame * (bytes_per_frame + bytes_per_mask);
  }
  int mask_address = source_address + bytes_per_frame;
  int destination_address = SCREEN_WIDTH * y + x;
  unsigned char color;
  for(scan_y = 0; scan_y < image_height; scan_y++){
    for(scan_x = 0; scan_x < image_width; scan_x++){
      if(x+scan_x>=0 && x+scan_x<96 && y+scan_y>=0 && y+scan_y<64){
        if(draw_mode == SPRITE_WITH_MASK){
          if( (pgm_read_byte(&bitmap[mask_address+(scan_x>>3)]) >> (scan_x%8) & 0b1) == 0){
            color = pgm_read_byte(&bitmap[ palette_offset + (pgm_read_byte(&bitmap[source_address + scan_x/ppb]) >> scan_x%ppb * bpp & factor) ] );
            screen_buffer[destination_address + scan_x] = color;
          }
        }else{
            color = pgm_read_byte(&bitmap[ palette_offset + (pgm_read_byte(&bitmap[source_address + scan_x/ppb]) >> scan_x%ppb * bpp & factor) ] );
            screen_buffer[destination_address + scan_x] = color;
        }
      }
    }
    source_address += image_width/ppb;
    mask_address += image_width/8;
    destination_address += SCREEN_WIDTH;
  }
}

