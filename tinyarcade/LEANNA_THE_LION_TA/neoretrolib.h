#define ALIGN_LEFT 0
#define ALIGN_CENTER 1
#define ALIGN_RIGHT 2

#define INRAM 0
#define INPROGMEM 1

void drawString(int8_t x, int8_t y, char const string[], const unsigned char fontBitmap[], int8_t color, int8_t bgcolor, int8_t align=0, int8_t location=0){
  char len;
  if(location==INPROGMEM){
    len = strlen_P(string); 
  }else{
    len = strlen(string); 
  }
  uint8_t image_width = pgm_read_byte(&fontBitmap[0]);//get image width  
  uint8_t image_height = pgm_read_byte(&fontBitmap[1]);//get image height  
  uint8_t font_width = pgm_read_byte(&fontBitmap[2]);//get image width  
  uint8_t font_height = pgm_read_byte(&fontBitmap[3]);//get image height  
  if(align==ALIGN_CENTER){
    x-=((font_width+1)*len)>>1;
  }else if(align==ALIGN_RIGHT){
    x-=(font_width+1)*len;
  }
  int8_t l=0;
  for(int8_t t=0; t<len; t++){
    char d;
    if(location==INPROGMEM){
      d = pgm_read_byte(string+t);
    }else{
      d = string[t];
    }
    if(d=='\n'){
      y+=(font_height+1);
      x=0;
      l=0;
      continue;
    }
    if(d<=32){d=0;}
    else{d-=32;}  
    uint8_t scan_x;
    uint8_t scan_y;   
    if(x+font_width+(l*(font_width+1))>=SCREEN_WIDTH){//move to next row
      y+=(font_height+1);
      x=0;
      l=0;
    }         
    int destination_address = SCREEN_WIDTH * y + x + (l*(font_width+1));
    int source_address = d * image_height + 4;
    for(scan_y = 0; scan_y < image_height; scan_y++){
      for(scan_x = 0; scan_x < image_width; scan_x++){
        if(x+scan_x+(l*(font_width+1))>=0 && x+scan_x+(l*(font_width+1))<SCREEN_WIDTH && y+scan_y>=0 && y+scan_y<SCREEN_HEIGHT){
          if( (pgm_read_byte(&fontBitmap[source_address + scan_x/8]) >> scan_x%8 & 0b1) == 1){
            screen_buffer[destination_address + scan_x] = color;
          }else if(bgcolor!=NULL){
            screen_buffer[destination_address + scan_x] = bgcolor;
          }
        }
      }
      source_address += image_width/8;
      destination_address += SCREEN_WIDTH;
    }
    l++;
  }
}

